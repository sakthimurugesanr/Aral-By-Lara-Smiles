import { mkdir, writeFile, unlink, stat } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import sharp from 'sharp';
import ffmpeg from 'ffmpeg-static';
import ffprobe from 'ffprobe-static';
const run = promisify(execFile);
const input = process.argv[2] || 'src/Assets/How Does Invisalign Work_ _ The Dental House_720p.mp4';
await mkdir('public/videos/technology', { recursive: true });
await mkdir('public/images/technology', { recursive: true });
const output = 'public/videos/technology/invisalign-explained.mp4';
await run(ffmpeg, ['-hide_banner','-loglevel','error','-y','-i',input,'-map','0:v:0','-an','-sn','-dn','-map_metadata','-1','-vf','scale=w=640:h=360:force_original_aspect_ratio=decrease:force_divisible_by=2,fps=24','-c:v','libx264','-preset','fast','-crf','28','-pix_fmt','yuv420p','-g','48','-movflags','+faststart','-threads','2',output]);
const frame = 'public/videos/technology/poster-frame.png';
await run(ffmpeg, ['-hide_banner','-loglevel','error','-y','-ss','8','-i',output,'-frames:v','1',frame]);
await sharp(frame).webp({ quality: 78 }).toFile('public/images/technology/invisalign-poster.webp');
await unlink(frame);
await sharp('src/Assets/Invisalign-clear-aligners.jpg').rotate().resize({ width: 960, height: 600, fit: 'cover', withoutEnlargement: true }).webp({ quality: 80 }).toFile('public/images/technology/clear-aligner.webp');
const { stdout } = await run(ffprobe.path, ['-v','quiet','-show_streams','-show_format','-of','json',output]);
const info = JSON.parse(stdout), video = info.streams.find(item => item.codec_type === 'video');
if (info.streams.some(item => item.codec_type === 'audio')) throw new Error('Unexpected audio track');
const result = { src:'/videos/technology/invisalign-explained.mp4', poster:'/images/technology/invisalign-poster.webp', width:video.width, height:video.height, duration:Number(info.format.duration), bytes:(await stat(output)).size, originalBytes:(await stat(input)).size };
await writeFile('src/lib/technology-video.json', JSON.stringify(result, null, 2) + '\n');
console.log(`Ambient Invisalign film: ${Math.round(result.originalBytes/1024)} → ${Math.round(result.bytes/1024)} KB; audio removed.`);
